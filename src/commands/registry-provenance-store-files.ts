/**
 * Which files inside a design system's `design/` directory can never be the real source of a component.
 *
 * A code ref may point at hand-authored source that lives under `design/` (a DLS page, a stylesheet,
 * `components/*.svelte`). It may not point at the design system's own files, because those only
 * restate the store and would let a component vouch for itself:
 *   (a) any `*.json` or `*.jsonl` file under the store (manifest, tokens, registry, shards, sidecars,
 *       inventories, rulings, logs);
 *   (b) anything under `rules/` (the promoted adherence rules);
 *   (c) files the `ui` CLI itself generates into the store, listed in `CLI_GENERATED_STORE_PATHS`.
 * Everything else under `design/` is allowed.
 */
import { sep } from "node:path";

export interface GeneratedStorePath {
  /** Relative to the store directory, forward slashes. */
  path: string;
  /** True when `path` is a directory and everything under it is generated. */
  directory?: boolean;
  /** The `ui` command (and file) that writes it. */
  writer: string;
}

/** Files the `ui` CLI writes into `design/`, with the writer of each. */
export const CLI_GENERATED_STORE_PATHS: readonly GeneratedStorePath[] = [
  { path: "soul.md", writer: "ui ds init (src/core/ds-soul.ts scaffold)" },
  { path: "DESIGN.md", writer: "ui ingest figma-ds (src/commands/ingest-figma-ds.ts)" },
  { path: "preview", directory: true, writer: "ui ds preview (src/commands/ds-preview-impl.ts, preview/specimen.html)" },
  { path: "guidelines", directory: true, writer: "ui ds guidelines build (src/commands/ds-guidelines-write.ts)" },
  { path: "harvest-inbox", directory: true, writer: "ui ds init / ui ds import (src/core/ds-fuel-line.ts)" },
];

/**
 * Why `relativePath` (relative to the store directory) is a design-system file, or undefined when it
 * may be a real source. Separators are normalised; the extension test ignores case.
 */
export function designSystemFileKind(relativePath: string): string | undefined {
  const rel = relativePath.split(sep).join("/");
  if (rel === "rules" || rel.startsWith("rules/")) return "promoted rules under rules/";
  if (/\.jsonl?$/i.test(rel)) return "a store data file (*.json / *.jsonl)";
  for (const g of CLI_GENERATED_STORE_PATHS) {
    if (rel === g.path || (g.directory === true && rel.startsWith(`${g.path}/`))) return `generated by ${g.writer}`;
  }
  return undefined;
}
