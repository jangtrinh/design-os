/**
 * ds-soul-proposed-region.ts - the one block of design/soul.md that `ui ds harvest-bans` may write.
 *
 *     ## Never (proposed)
 *
 *     <!-- ds-harvest-bans:begin sha=<12 hex> lines=<4 hex per line> -->
 *     ...generated lines...
 *     <!-- ds-harvest-bans:end -->
 *
 * Only the text between the two markers is the tool's. Every other byte of the file, an owner note between
 * the heading and the markers, or an owner bullet that starts with a probe id, is never read as generated
 * and never rewritten. The begin marker carries a hash of the generated text: when the text between the
 * markers no longer matches it, someone edited inside, and the write is refused (PROPOSED_BLOCK_EDITED)
 * with the differing lines named; nothing is written. A `## Never (proposed)` section without markers
 * gets the region appended at its end. The tool never writes the binding `## Never` section.
 */
import { DSError } from "./design-system.js";
import { blockSha, sha256Hex } from "./ds-guidelines-render.js";
import { sectionBody } from "./ds-soul.js";

export const PROPOSED_NEVER_HEADING = "## Never (proposed)";
export const PROPOSED_BLOCK_EDITED = "PROPOSED_BLOCK_EDITED";
const BEGIN_PREFIX = "<!-- ds-harvest-bans:begin";
const END_MARKER = "<!-- ds-harvest-bans:end -->";
const BEGIN_RE = /^<!-- ds-harvest-bans:begin sha=([0-9a-f]{12}) lines=([0-9a-f]{4}(?:,[0-9a-f]{4})*)? -->[ \t]*$/;
const PROPOSED_HEADING_RE = /^## Never \(proposed\)[ \t]*\r?$/m;
export const REGION_INSTRUCTION =
  "<!-- Generated by `ui ds harvest-bans`: only the lines between the markers are rewritten, on every harvest. To promote a ban, move its bullet under '## Never' and run `ui ds harvest-bans --accept <NS-id>` for its machine rule. Write your own notes outside the markers. -->";

/** Probe ids (`NS-01`) named by the bullets of the BINDING `## Never` section, in order, without repeats. */
export function bindingNeverIds(text: string): string[] {
  const section = sectionBody(text, "Never");
  if (section === null) return [];
  const ids: string[] = [];
  for (const m of section.body.matchAll(/^[ \t]*[-*][ \t]+(.*)$/gm)) {
    for (const id of (m[1] ?? "").match(/\bNS-\d\d\b/g) ?? []) if (!ids.includes(id)) ids.push(id);
  }
  return ids;
}

const fingerprint = (line: string): string => sha256Hex(line).slice(0, 4);
const clipLine = (s: string): string => (s.length > 80 ? `${s.slice(0, 79)}…` : s);

interface Region { start: number; end: number; interior: string[]; interiorLine: number; sha: string; fingerprints: string[] }

/** The region of `text`, null when there is none; damaged markers are an error (the tool cannot tell what is its own). */
function findRegion(text: string, where: string): Region | null {
  const lines = text.split("\n");
  const begins: number[] = [];
  const ends: number[] = [];
  lines.forEach((l, i) => {
    const t = l.replace(/\r$/, "");
    if (t.startsWith(BEGIN_PREFIX)) begins.push(i);
    else if (t.trim() === END_MARKER) ends.push(i);
  });
  if (begins.length === 0 && ends.length === 0) return null;
  const damaged = (why: string): DSError => new DSError(PROPOSED_BLOCK_EDITED,
    `${where}: the ds-harvest-bans markers are damaged (${why}), so the harvest wrote nothing. Next: restore the begin marker line (\`${BEGIN_PREFIX} sha=... lines=... -->\`) and the end marker line (\`${END_MARKER}\`), or delete both markers and the lines between them, then run the harvest again.`);
  if (begins.length !== 1 || ends.length !== 1) throw damaged(`${begins.length} begin and ${ends.length} end marker line(s), expected one of each`);
  const [b, e] = [begins[0] as number, ends[0] as number];
  const m = BEGIN_RE.exec((lines[b] as string).replace(/\r$/, ""));
  if (e < b) throw damaged("the end marker comes before the begin marker");
  if (m === null) throw damaged("the begin marker line was edited");
  const offsetOf = (n: number): number => lines.slice(0, n).reduce((sum, l) => sum + l.length + 1, 0);
  const startOffset = offsetOf(b);
  const endOffset = offsetOf(e) + (lines[e] as string).replace(/\r$/, "").length;
  return {
    start: startOffset, end: endOffset, interiorLine: b + 2,
    interior: lines.slice(b + 1, e).map((l) => l.replace(/\r$/, "")),
    sha: m[1] as string, fingerprints: (m[2] ?? "").split(",").filter((x) => x !== ""),
  };
}

/** Throws when the text between the markers is not what the begin marker's hash says the tool wrote. */
function assertUntouched(r: Region, where: string): void {
  if (blockSha(r.interior.join("\n")) === r.sha) return;
  const known = new Map<string, number>();
  for (const f of r.fingerprints) known.set(f, (known.get(f) ?? 0) + 1);
  const differing: string[] = [];
  r.interior.forEach((l, i) => {
    const f = fingerprint(l);
    const n = known.get(f) ?? 0;
    if (n > 0) known.set(f, n - 1);
    else differing.push(`line ${r.interiorLine + i}: "${clipLine(l)}" (edited or added)`);
  });
  const missing = [...known.values()].reduce((a, b) => a + b, 0);
  if (missing > 0) differing.push(`${missing} generated line(s) removed or changed from their original text`);
  throw new DSError(PROPOSED_BLOCK_EDITED,
    `${where}: the text between the ds-harvest-bans markers was edited by hand, so the harvest wrote nothing. Differing: ${differing.join("; ") || "the text no longer matches its hash"}. Next: move your text outside the markers (above the begin marker or below the end marker), then run the harvest again.`);
}

function regionText(lines: readonly string[], eol: string): string {
  const interior = [REGION_INSTRUCTION, ...lines];
  const begin = `${BEGIN_PREFIX} sha=${blockSha(interior.join("\n"))} lines=${interior.map(fingerprint).join(",")} -->`;
  return [begin, ...interior, END_MARKER].join(eol);
}

/**
 * Write the generated lines into a soul and touch nothing else. An existing region is replaced between its
 * markers (refused when its text was edited); a `## Never (proposed)` section without markers gets the region
 * appended at its end; with neither, the section is created right after the binding `## Never` (end of file
 * when there is none). With no lines and no region there is nothing to write and the text is returned as is.
 */
export function applyProposedRegion(text: string, lines: readonly string[], where = "design/soul.md"): string {
  const eol = text.includes("\r\n") ? "\r\n" : "\n";
  const region = findRegion(text, where);
  if (region !== null) {
    assertUntouched(region, where);
    return text.slice(0, region.start) + regionText(lines, eol) + text.slice(region.end);
  }
  if (lines.length === 0) return text;
  const block = regionText(lines, eol);
  const heading = PROPOSED_HEADING_RE.exec(text);
  if (heading !== null) {
    const after = heading.index + heading[0].length;
    const next = /^##[ \t]+\S/m.exec(text.slice(after));
    const sectionEnd = next === null ? text.length : after + next.index;
    const lastText = text.slice(after, sectionEnd).replace(/\s+$/, "");
    const at = after + lastText.length;
    return text.slice(0, at) + eol + eol + block + text.slice(at);
  }
  const never = /^##[ \t]+Never[ \t]*\r?$/m.exec(text);
  const next = never === null ? null : /^##[ \t]+\S/m.exec(text.slice(never.index + never[0].length));
  const section = [PROPOSED_NEVER_HEADING, "", block].join(eol);
  if (never !== null && next !== null) {
    const at = never.index + never[0].length + next.index;
    return text.slice(0, at) + section + eol + eol + text.slice(at);
  }
  return (text.endsWith("\n") ? text : text + eol) + eol + section + eol;
}
