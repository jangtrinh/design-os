/**
 * ds-soul-proposed-region.ts - the one block of design/soul.md that `ui ds harvest-bans` may write.
 *
 *     ## Never (proposed)
 *
 *     <!-- ds-harvest-bans:begin sha=<12 hex> lines=<8 hex per line> -->
 *     ...generated lines...
 *     <!-- ds-harvest-bans:end -->
 *
 * Only the text between the two markers is the tool's, and only inside the `## Never (proposed)` section.
 * Every other byte of the file, an owner note next to the region or an owner bullet that starts with a probe
 * id, is never read as generated and never rewritten.
 *
 * Between the markers the owner may cut whole generated lines (moving a bullet under `## Never` is exactly
 * that), reorder them and add or remove blank lines; the next harvest regenerates the region, and a line that
 * was deleted without being moved comes back while its count is still zero. A line the tool did not write (an
 * edited or an added one) is refused (PROPOSED_BLOCK_EDITED) with the line named; nothing is written. Marker
 * lines inside a fenced code block are text. Markers anywhere but under `## Never (proposed)` are refused: the
 * tool never writes the binding `## Never`. A `## Never (proposed)` section without markers gets the region
 * appended at its end.
 */
import { DSError } from "./design-system.js";
import { blockSha, sha256Hex } from "./ds-guidelines-render.js";

export const PROPOSED_NEVER_HEADING = "## Never (proposed)";
export const PROPOSED_BLOCK_EDITED = "PROPOSED_BLOCK_EDITED";
const BEGIN_PREFIX = "<!-- ds-harvest-bans:begin";
const END_MARKER = "<!-- ds-harvest-bans:end -->";
const BEGIN_RE = /^<!-- ds-harvest-bans:begin sha=([0-9a-f]{12}) lines=([0-9a-f]{8}(?:,[0-9a-f]{8})*)? -->$/;
export const REGION_INSTRUCTION =
  "<!-- Generated by `ui ds harvest-bans`: only the lines between the markers are rewritten, on every harvest. To promote a ban, cut its bullet out of this region and paste it under '## Never', then run `ui ds harvest-bans --accept <NS-id>` for its machine rule. A line you delete without moving it comes back on the next harvest while its count is still zero. Write your own notes outside the markers. -->";

/** One line of a soul with what the scan knows about it. */
interface Ln { text: string; start: number; end: number; fence: boolean; heading: string }

/** Lines with their offsets, fenced-code state and the nearest `#`/`##` heading above (a marker in a fence is text). `unclosed` is the 1-based line that opened a fence the file never closes. */
function scan(text: string): Ln[] & { unclosed?: number } {
  const out: Ln[] & { unclosed?: number } = [];
  let fence: { ch: string; len: number; line: number } | null = null;
  let heading = "";
  let start = 0;
  for (const raw of text.split("\n")) {
    const t = raw.replace(/\r$/, "");
    const open = /^ {0,3}(`{3,}|~{3,})/.exec(t);
    let inFence = fence !== null;
    if (fence === null && open !== null) { fence = { ch: (open[1] as string)[0] as string, len: (open[1] as string).length, line: out.length + 1 }; inFence = true; }
    else if (fence !== null && new RegExp(`^ {0,3}\\${fence.ch}{${fence.len},}[ \\t]*$`).test(t)) fence = null;
    if (!inFence && /^#{1,2}[ \t]+\S/.test(t)) heading = t.trimEnd();
    out.push({ text: t, start, end: start + t.length, fence: inFence, heading });
    start += raw.length + 1;
  }
  if (fence !== null) out.unclosed = fence.line;
  return out;
}
/** Line that opened a code fence the soul never closes (everything after it is fence text), else null. */
export function unclosedFence(text: string): number | null {
  return scan(text).unclosed ?? null;
}
const isProposedHeading = (l: Ln): boolean => !l.fence && l.text.trimEnd() === PROPOSED_NEVER_HEADING;
const isBinding = (heading: string): boolean => /^##[ \t]+Never[ \t]*$/.test(heading);
const isBegin = (l: Ln): boolean => !l.fence && l.text.trim().startsWith(BEGIN_PREFIX);
const isEnd = (l: Ln): boolean => !l.fence && l.text.trim() === END_MARKER;

/** Probe ids (`NS-01`) named by bullets of the BINDING `## Never` section; lines between harvest markers or in a fence are never read. */
export function bindingNeverIds(text: string): string[] {
  const ids: string[] = [];
  let inRegion = false;
  for (const l of scan(text)) {
    if (isBegin(l)) { inRegion = true; continue; }
    if (isEnd(l)) { inRegion = false; continue; }
    if (inRegion || l.fence || !isBinding(l.heading) || l.text.trimEnd() === l.heading) continue;
    const m = /^[ \t]*[-*][ \t]+(.*)$/.exec(l.text);
    for (const id of m?.[1]?.match(/\bNS-\d\d\b/g) ?? []) if (!ids.includes(id)) ids.push(id);
  }
  return ids;
}

const fingerprint = (line: string): string => sha256Hex(line).slice(0, 8);
const clipLine = (s: string): string => (s.length > 80 ? `${s.slice(0, 79)}…` : s);

interface Region { start: number; end: number; interior: { text: string; line: number }[]; fingerprints: string[] }
const refuse = (msg: string): DSError => new DSError(PROPOSED_BLOCK_EDITED, msg);
const PLACE_NEXT = `put the '${PROPOSED_NEVER_HEADING}' heading back above the begin marker, or delete both markers and the lines between them, then run the harvest again.`;

/** Marker lines of a scan: null when there are none; damaged or misplaced markers are an error. */
function findRegion(lines: Ln[], where: string): Region | null {
  const begins = lines.flatMap((l, i) => (isBegin(l) ? [i] : []));
  const ends = lines.flatMap((l, i) => (isEnd(l) ? [i] : []));
  if (begins.length === 0 && ends.length === 0) return null;
  const damaged = (why: string): DSError => refuse(
    `${where}: the ds-harvest-bans markers are damaged (${why}), so the harvest wrote nothing. Next: restore the begin marker line (\`${BEGIN_PREFIX} sha=... lines=... -->\`) and the end marker line (\`${END_MARKER}\`), or delete both markers and the lines between them, then run the harvest again.`);
  if (begins.length !== 1 || ends.length !== 1) throw damaged(`${begins.length} begin and ${ends.length} end marker line(s), expected one of each`);
  const [b, e] = [begins[0] as number, ends[0] as number];
  if (e < b) throw damaged("the end marker comes before the begin marker");
  const m = BEGIN_RE.exec((lines[b] as Ln).text.trim());
  if (m === null) throw damaged("the begin marker line was edited");
  const where2 = [lines[b] as Ln, lines[e] as Ln].find((l) => l.heading !== PROPOSED_NEVER_HEADING);
  if (where2 !== undefined) {
    throw refuse(`${where}: the ds-harvest-bans markers sit under '${where2.heading === "" ? "no heading" : where2.heading}' (line ${(lines.indexOf(where2) + 1)}), not under '${PROPOSED_NEVER_HEADING}', so the harvest wrote nothing. Next: ${PLACE_NEXT}`);
  }
  return {
    start: (lines[b] as Ln).start, end: (lines[e] as Ln).end,
    interior: lines.slice(b + 1, e).map((l, i) => ({ text: l.text, line: b + 2 + i })),
    fingerprints: (m[2] ?? "").split(",").filter((x) => x !== ""),
  };
}

/** Throws when a non-blank line between the markers is not one the tool wrote (an edited or an added line). */
function assertOnlyGenerated(r: Region, where: string): void {
  const known = new Map<string, number>();
  for (const f of r.fingerprints) known.set(f, (known.get(f) ?? 0) + 1);
  const foreign: string[] = [];
  for (const l of r.interior) {
    if (l.text.trim() === "") continue;
    const f = fingerprint(l.text);
    const n = known.get(f) ?? 0;
    if (n > 0) known.set(f, n - 1);
    else foreign.push(`line ${l.line}: "${clipLine(l.text)}"`);
  }
  if (foreign.length === 0) return;
  throw refuse(`${where}: the text between the ds-harvest-bans markers holds a line the harvest did not write (edited or added), so the harvest wrote nothing. Differing: ${foreign.join("; ")}. Next: move your text outside the markers (above the begin marker or below the end marker), or put the original line back; you may cut whole generated lines, reorder them and add blank lines.`);
}

function regionText(lines: readonly string[], eol: string): string {
  const interior = [REGION_INSTRUCTION, ...lines];
  const begin = `${BEGIN_PREFIX} sha=${blockSha(interior.join("\n"))} lines=${interior.map(fingerprint).join(",")} -->`;
  return [begin, ...interior, END_MARKER].join(eol);
}

/** `{ line, heading }` of a harvest region that is not under `## Never (proposed)` (for the soul check), else null. */
export function misplacedRegion(text: string): { line: number; heading: string } | null {
  const lines = scan(text);
  const at = lines.findIndex(isBegin);
  const l = lines[at];
  return l === undefined || l.heading === PROPOSED_NEVER_HEADING ? null : { line: at + 1, heading: l.heading };
}

/**
 * Write the generated lines into a soul and touch nothing else. An existing region is replaced between its
 * markers (refused when it holds a line the tool did not write, or sits outside `## Never (proposed)`); a
 * `## Never (proposed)` section without markers gets the region appended at its end; with neither, the section
 * is created right after the binding `## Never` (end of file when there is none). With no lines and no region
 * there is nothing to write and the text is returned as is.
 */
export function applyProposedRegion(text: string, lines: readonly string[], where = "design/soul.md"): string {
  const eol = text.includes("\r\n") ? "\r\n" : "\n";
  const scanned = scan(text);
  // End of file does not close a fence: the tool cannot know where the owner meant it to end, and every later line
  // (the heading, the markers) would be unreadable, so the tool would append another section on every run.
  if (scanned.unclosed !== undefined) {
    throw refuse(`${where}: the code fence opened on line ${scanned.unclosed} is never closed, so the harvest wrote nothing. Next: close the fence (add a closing \`\`\` or ~~~ line), then run the harvest again.`);
  }
  const region = findRegion(scanned, where);
  if (region !== null) {
    assertOnlyGenerated(region, where);
    return text.slice(0, region.start) + regionText(lines, eol) + text.slice(region.end);
  }
  if (lines.length === 0) return text;
  const block = regionText(lines, eol);
  const sectionEnd = (from: number): number => {
    const next = scanned.findIndex((l, i) => i > from && !l.fence && /^#{1,2}[ \t]+\S/.test(l.text));
    return next === -1 ? text.length : (scanned[next] as Ln).start;
  };
  const heading = scanned.findIndex(isProposedHeading);
  if (heading !== -1) {
    const end = sectionEnd(heading);
    const at = (scanned[heading] as Ln).end + text.slice((scanned[heading] as Ln).end, end).replace(/\s+$/, "").length;
    return text.slice(0, at) + eol + eol + block + text.slice(at);
  }
  const never = scanned.findIndex((l) => !l.fence && /^##[ \t]+Never[ \t]*$/.test(l.text));
  const section = [PROPOSED_NEVER_HEADING, "", block].join(eol);
  if (never !== -1 && sectionEnd(never) < text.length) {
    const at = sectionEnd(never);
    return text.slice(0, at) + section + eol + eol + text.slice(at);
  }
  return (text.endsWith("\n") ? text : text + eol) + eol + section + eol;
}
