/**
 * mode-invisible-surface — the cases that broke or misled the first compositing
 * implementation: hostile input, where an outer ring paints, backdrops the text
 * only partly names, the exact thresholds, and finding identity (id, severity, line).
 *
 * Every assertion drives the real check. Nothing here recomputes its comparison.
 */
import { describe, expect, it } from "vitest";
import { checkModeInvisibleSurface, inspectInvisibleSurface } from "../src/core/taste-checks-invisible-surface.js";
import { lintTaste } from "../src/core/taste-lint.js";

/** Run `fn` and fail if it took a second or more: the blow-ups this guards against take ten or never finish. */
function withinOneSecond<T>(fn: () => T): T {
  const t0 = performance.now();
  const out = fn();
  expect(performance.now() - t0).toBeLessThan(1000);
  return out;
}

describe("mode-invisible-surface — hostile and malformed input", () => {
  it.each([
    { name: "an element left open before <html>", html: '<div class="wrap"><html><body><span class="bg-white/10">x</span></body></html>', expected: 1 },
    { name: "text and a doctype before <html>", html: '<p>Generated by tool<!DOCTYPE html><html lang="en"><body><div class="border border-white/10">x</div></body></html>', expected: 1 },
    { name: "a broken tag before <html>", html: "<d)border-black/5><html>", expected: 0 },
  ])("terminates on $name and finds what a browser would", ({ html, expected }) => {
    expect(withinOneSecond(() => checkModeInvisibleSurface(html))).toHaveLength(expected);
  });

  it("evaluates a 200-deep descendant chain whose leftmost compound never matches in linear time", () => {
    const depth = 200;
    const html =
      "<style>.nope div div div div div{background:#111}.pill{background:rgba(255,255,255,.08)}</style><body>" +
      "<div>".repeat(depth) + '<span class="pill">x</span>' + "</div>".repeat(depth) + "</body>";
    expect(withinOneSecond(() => checkModeInvisibleSurface(html))).toHaveLength(1); // the pill sits on the white page
  });

  it("reads 100 KB of unclosed '<a b ' tags without stalling", () => {
    const html = "<a b ".repeat(20_000);
    expect(html.length).toBeGreaterThanOrEqual(100_000);
    expect(withinOneSecond(() => checkModeInvisibleSurface(html))).toHaveLength(0);
  });

  it("survives a 20,000-deep nest and a var() cycle", () => {
    const deep = "<div>".repeat(20_000) + '<span class="bg-white/10">x</span>';
    expect(() => withinOneSecond(() => checkModeInvisibleSurface(deep))).not.toThrow();
    const cycle = "<style>:root{--a:var(--b);--b:var(--a)} body{background:var(--a)} .p{background:rgba(255,255,255,.05)}</style><span class=\"p\">x</span>";
    expect(withinOneSecond(() => checkModeInvisibleSurface(cycle))).toHaveLength(0); // an unresolvable page is undecidable, not white
  });
});

describe("mode-invisible-surface — an outer ring, outline or shadow paints over the PARENT", () => {
  const onBlackPage = (card: string): string => `<style>body{background:#0b0b0b}.c{background:#fafafa;${card}}</style><body><div class="c">x</div></body>`;

  it.each([
    { name: "a white ring around a light card on a black page", html: '<html><body class="bg-black"><div class="bg-white ring-1 ring-white/10">card</div></body></html>' },
    { name: "an outer white box-shadow", html: onBlackPage("box-shadow:0 0 0 1px rgba(255,255,255,.08)") },
    { name: "an outer white outline", html: onBlackPage("outline:1px solid rgba(255,255,255,.08)") },
  ])("does not flag $name: the ring sits on black, not on the card", ({ html }) => {
    const r = inspectInvisibleSurface(html);
    expect(r.findings).toHaveLength(0);
    expect(r.stats.visible).toBe(1); // judged and composited over the black parent, not skipped
  });

  it("flags the mirror — a white outer ring on a dark card inside a light page — once, as a warning", () => {
    const html = '<body class="bg-white">\n<div class="bg-slate-900 ring-1 ring-white/10">card</div>\n</body>';
    const f = checkModeInvisibleSurface(html);
    expect(f).toHaveLength(1);
    expect(f[0]).toMatchObject({ checkId: "mode-invisible-surface", severity: "warning", line: 2 });
    expect(f[0]?.message).toContain("outside the element");
  });

  it("keeps a black ring on a light page quiet: black on light is the correct hairline", () => {
    expect(checkModeInvisibleSurface('<body class="bg-white"><div class="bg-slate-900 ring-1 ring-black/10">card</div></body>')).toHaveLength(0);
  });

  it("flags an outer box-shadow and an outline as warnings on a light parent", () => {
    const shadow = checkModeInvisibleSurface('<style>body{background:#fff}.c{box-shadow:0 0 0 1px rgba(255,255,255,.08)}</style><body><div class="c">x</div></body>');
    const outline = checkModeInvisibleSurface('<style>body{background:#fff}.c{outline:1px solid rgba(255,255,255,.08)}</style><body><div class="c">x</div></body>');
    expect(shadow.map((f) => f.severity)).toEqual(["warning"]);
    expect(outline.map((f) => f.severity)).toEqual(["warning"]);
  });

  it("keeps borders, fills and inset shadows as errors, measured on the element's own surface", () => {
    const light = '<body class="bg-white">';
    expect(checkModeInvisibleSurface(`${light}<div class="border border-white/10">x</div></body>`).map((f) => f.severity)).toEqual(["error"]);
    expect(checkModeInvisibleSurface(`${light}<div class="bg-white/5">x</div></body>`).map((f) => f.severity)).toEqual(["error"]);
    expect(checkModeInvisibleSurface(`${light}<div class="ring-1 ring-inset ring-white/10">x</div></body>`).map((f) => f.severity)).toEqual(["error"]);
    const inset = checkModeInvisibleSurface('<style>body{background:#fff}.c{box-shadow:inset 0 0 0 1px rgba(255,255,255,.08)}</style><body><div class="c">x</div></body>');
    expect(inset.map((f) => f.severity)).toEqual(["error"]);
    // …and a dark card's own white border is visible against the card, whatever the page is
    expect(checkModeInvisibleSurface(`${light}<div class="bg-slate-900 border border-white/10">x</div></body>`)).toHaveLength(0);
  });
});

describe("mode-invisible-surface — backdrops the text only partly names", () => {
  const lightPageFinding = (html: string): void => {
    const f = checkModeInvisibleSurface(html);
    expect(f).toHaveLength(1);
    expect(f[0]).toMatchObject({ checkId: "mode-invisible-surface", severity: "error" });
  };

  it("a page background themed through var() and redefined under .dark", () => {
    lightPageFinding('<style>:root{--bg:#fff}.dark{--bg:#0b0b0b}body{background:var(--bg)}</style><body><div class="border border-white/10">x</div></body>');
  });
  it("a shadcn theme-token body (bg-background) with no dark class", () => {
    lightPageFinding('<body class="bg-background"><div class="border border-white/10">x</div></body>');
  });
  it("a pale chromatic Tailwind card (bg-blue-50)", () => {
    lightPageFinding('<body class="bg-white"><div class="bg-blue-50"><div class="border border-white/10">x</div></div></body>');
  });
  it("a page with a url() texture over a white colour", () => {
    lightPageFinding("<style>body{background:#fff;background-image:url(noise.png)}</style><body><div class=\"border border-white/10\">x</div></body>");
  });
  it("a 90%-opaque white card (bg-opacity)", () => {
    lightPageFinding('<body class="bg-white"><div class="bg-white bg-opacity-90"><div class="border border-white/10">x</div></div></body>');
  });
  it("a utility applied through @apply", () => {
    lightPageFinding('<style>.btn{@apply border border-white/10}</style><body class="bg-white"><button class="btn">x</button></body>');
  });

  it("composites a translucent dark dock over an UNREADABLE stage instead of skipping the tint", () => {
    const html = [
      "<style>",
      "#stage{background:var(--missing)}",
      "#dock{background:rgba(20,22,28,.88)}",
      ".dot{background:rgba(255,255,255,.06)}",
      "</style>",
      '<body><div id="stage"><div id="dock"><span class="dot">x</span></div></div></body>',
    ].join("\n");
    const r = inspectInvisibleSurface(html);
    expect(r.findings).toHaveLength(0);
    expect(r.stats).toEqual({ invisible: 0, visible: 1, undecided: 0 }); // composited, not bailed
  });

  it("reads an oklch() card: a dark one shows the pill, a pale one does not", () => {
    const onCard = (card: string): string =>
      `<style>.card{background:${card}}.pill{background:rgba(255,255,255,.08)}</style><body class="bg-white"><div class="card"><span class="pill">x</span></div></body>`;
    expect(inspectInvisibleSurface(onCard("oklch(0.2 0 0)"))).toMatchObject({ findings: [], stats: { visible: 1 } });
    expect(checkModeInvisibleSurface(onCard("oklch(97% 0.01 250)"))).toHaveLength(1);
  });

  it.each([
    { tint: "white", css: ".dot{background:rgba(255,255,255,.06)}" },
    { tint: "black", css: ".dot{background:rgba(0,0,0,.06)}" },
  ])("skips a $tint tint whose whole backdrop is unreadable: neither end of the interval may decide alone", ({ css }) => {
    const r = inspectInvisibleSurface(`<style>#stage{background:var(--missing)}${css}</style><body><div id="stage"><span class="dot">x</span></div></body>`);
    expect(r.findings).toHaveLength(0);
    expect(r.stats).toEqual({ invisible: 0, visible: 0, undecided: 1 });
  });

  it("carries a gradient that fades to transparent as coverage anywhere from none to full", () => {
    // Over a dark page the glow is light where it is opaque and dark where it fades: no single backdrop.
    const glow = "radial-gradient(circle, rgba(255,255,255,.9), transparent)";
    const alone = `<style>body{background:#111}.hero{background:${glow}}.pill{background:rgba(255,255,255,.08)}</style><body><div class="hero"><span class="pill">x</span></div></body>`;
    const overColour = `<style>.hero{background:${glow}, #111}.pill{background:rgba(255,255,255,.08)}</style><body><div class="hero"><span class="pill">x</span></div></body>`;
    for (const html of [alone, overColour]) expect(inspectInvisibleSurface(html)).toMatchObject({ findings: [], stats: { undecided: 1 } });
  });

  it("reads a url() image as its colour fallback, and a photo with no fallback as unreadable", () => {
    const onCard = (bg: string): string => `<style>.card{background:${bg}}.pill{background:rgba(255,255,255,.08)}</style><body class="bg-white"><div class="card"><span class="pill">x</span></div></body>`;
    expect(inspectInvisibleSurface(onCard("#18181b url(grain.png)"))).toMatchObject({ findings: [], stats: { visible: 1 } });
    expect(inspectInvisibleSurface(onCard("url(photo.jpg)"))).toMatchObject({ findings: [], stats: { undecided: 1 } });
  });

  it("gives a fragment the html > body a browser would, so root rules still land", () => {
    const root = (rule: string): string => `<style>${rule}.x{background:rgba(0,0,0,.05)}</style><div class="x">x</div>`;
    expect(checkModeInvisibleSurface(root("html{background:#0b0b0b}"))).toHaveLength(1); // black on a dark page
    expect(checkModeInvisibleSurface(root(":root{background:#0b0b0b}"))).toHaveLength(1);
    expect(checkModeInvisibleSurface(root("body{background:#0b0b0b}"))).toHaveLength(1);
    expect(checkModeInvisibleSurface(root("html{background:#fff}"))).toHaveLength(0); // black on a light page is the correct hairline
  });

  it("applies bg-opacity: a 10%-opaque dark card is as light as the page under it", () => {
    const card = (cls: string): string => `<body class="bg-white"><div class="${cls}"><span class="bg-white/10">x</span></div></body>`;
    expect(checkModeInvisibleSurface(card("bg-slate-900"))).toHaveLength(0); // dark card: the pill shows
    expect(checkModeInvisibleSurface(card("bg-slate-900 bg-opacity-10"))).toHaveLength(1); // nearly transparent: white on white
  });
});

describe("mode-invisible-surface — the thresholds, driven through the real check", () => {
  const grey = (value: number): string => `rgb(${value},${value},${value})`;
  const pillOnCard = (card: string, alpha: number): string =>
    `<style>.card{background:${card}}.pill{background:rgba(255,255,255,${alpha})}</style><body class="bg-white"><div class="card"><span class="pill">x</span></div></body>`;

  it("a white tint is an edge once it moves the backdrop by 0.03 of luma: 5% on mid-grey vanishes, 7% shows", () => {
    expect(checkModeInvisibleSurface(pillOnCard(grey(128), 0.05))).toHaveLength(1);
    expect(checkModeInvisibleSurface(pillOnCard(grey(128), 0.07))).toHaveLength(0);
  });

  it("the dark/light polarity line is luma 0.25: white 2% on grey 61 is a glass layer, on grey 66 it vanishes", () => {
    expect(checkModeInvisibleSurface(pillOnCard(grey(61), 0.02))).toHaveLength(0);
    expect(checkModeInvisibleSurface(pillOnCard(grey(66), 0.02))).toHaveLength(1);
  });

  it("the alpha floor is 0.15: a tint at 14% is judged, one at 15% never is", () => {
    expect(inspectInvisibleSurface(pillOnCard("#fff", 0.14)).findings).toHaveLength(1);
    expect(inspectInvisibleSurface(pillOnCard("#fff", 0.15))).toEqual({ findings: [], stats: { invisible: 0, visible: 0, undecided: 0 } });
  });
});

describe("mode-invisible-surface — colour syntaxes a white tint can be written in", () => {
  const page = (value: string): string => `<body class="bg-white">\n<div style="border-color:${value}">x</div>\n</body>`;

  it.each([
    "#fff1", "#ffffff11", "rgb(255 255 255 / 8%)", "rgba(255,255,255,8%)", "rgba(255, 255, 255, 0.08)",
    "hsla(0, 0%, 100%, 0.08)", "hsl(0 0% 100% / 8%)",
  ])("sees %s on a white page", (value) => {
    const f = checkModeInvisibleSurface(page(value));
    expect(f).toHaveLength(1);
    expect(f[0]).toMatchObject({ checkId: "mode-invisible-surface", severity: "error", line: 2 });
  });

  // The cascade hands over minified values (`rgb(255 255 255/8%)`, `hsl(0 0%100%/8%)`): the same syntaxes in a stylesheet.
  it.each([
    "#fff1", "#ffffff11", "rgb(255 255 255 / 8%)", "rgba(255,255,255,8%)", "hsla(0, 0%, 100%, 0.08)", "hsl(0 0% 100% / 8%)",
    "oklch(1 0 0 / 8%)",
  ])("sees %s written in a stylesheet rule, on the declaration's line", (value) => {
    const f = checkModeInvisibleSurface(`<style>\nbody{background:#fff}\n.x{border-color:${value}}\n</style>\n<body><div class="x">x</div></body>`);
    expect(f).toHaveLength(1);
    expect(f[0]).toMatchObject({ checkId: "mode-invisible-surface", severity: "error", line: 3 });
  });

  it("does not take an opaque or fully transparent colour for a tint", () => {
    for (const value of ["#fff", "rgb(255 255 255)", "rgba(255,255,255,0)", "transparent", "rgba(255,255,255,.2)"]) {
      expect(checkModeInvisibleSurface(page(value))).toHaveLength(0);
    }
  });
});

describe("mode-invisible-surface — finding identity", () => {
  it("reports checkId, severity and the line of the utility that paints the tint", () => {
    const html = ['<body class="bg-white">', "<p>text</p>", '<div class="border border-white/10">x</div>', "</body>"].join("\n");
    expect(checkModeInvisibleSurface(html)).toMatchObject([{ checkId: "mode-invisible-surface", axis: "Depth/Surface", severity: "error", line: 3 }]);
  });

  it("reports the line of a stylesheet declaration, once, however many elements the rule reaches", () => {
    const html = ["<style>", "body { background: #fff }", ".pill {", "  background: rgba(255,255,255,0.08);", "}", "</style>", '<body><i class="pill">a</i><i class="pill">b</i><i class="pill">c</i></body>'].join("\n");
    expect(checkModeInvisibleSurface(html)).toMatchObject([{ checkId: "mode-invisible-surface", severity: "error", line: 4 }]);
  });

  it("describes a coloured swatch as a coloured surface, not as a dark-mode background", () => {
    const f = checkModeInvisibleSurface('<body class="bg-white"><div style="background:hsl(220 100% 25%)"><span class="border-black/5">x</span></div></body>');
    expect(f).toHaveLength(1);
    expect(f[0]?.message).toContain("dark coloured surface");
    expect(f[0]?.message).not.toContain("dark-mode background");
  });

  it("is registered in lintTaste with the severity split intact", () => {
    const r = lintTaste('<body class="bg-white"><div class="border border-white/10 ring-1 ring-white/10">x</div></body>');
    const mine = r.findings.filter((f) => f.checkId === "mode-invisible-surface");
    expect(mine.map((f) => f.severity).sort()).toEqual(["error", "warning"]);
  });
});
